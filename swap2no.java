public class swap2no {
    public static void main(String[] args){
        int m =10;
        int n =15;
        System.out.println("before swapping m is "+m+ " and n is "+n);
        int temp = m;
        m=n;
        n= temp;
        System.out.println("after swapping m is "+m+" and n is "+n);
    }
    
}
